  const D = { fr, en };
  let lang = "fr";

  function setLang(l) { lang = D[l] ? l : "fr"; document.documentElement.lang = lang; }
  // pick: configured language if fr|en, else the browser's.
  function detect(cfgLang) {
    if (D[cfgLang]) return cfgLang;
    const nav = (navigator.languages && navigator.languages[0]) || navigator.language || "fr";
    return nav.toLowerCase().startsWith("fr") ? "fr" : (nav.toLowerCase().startsWith("en") ? "en" : "fr");
  }
  function t(k, v) {
    const s = D[lang][k] !== undefined ? D[lang][k] : (D.fr[k] !== undefined ? D.fr[k] : k);
    return s.replace(/\{(\w+)\}/g, (m, x) => (v && x in v ? v[x] : m));
  }
  function tp(k, n, v) {
    const cat = new Intl.PluralRules(lang).select(n) === "one" ? "one" : "other";
    return t(k + "." + cat, Object.assign({ n: n }, v));
  }
  // Translate static markup: data-i18n (text), data-i18n-aria, data-i18n-ph.
  function apply(root) {
    (root || document).querySelectorAll("[data-i18n]").forEach(function (e) { e.textContent = t(e.dataset.i18n); });
    (root || document).querySelectorAll("[data-i18n-aria]").forEach(function (e) { e.setAttribute("aria-label", t(e.dataset.i18nAria)); });
    (root || document).querySelectorAll("[data-i18n-ph]").forEach(function (e) { e.setAttribute("placeholder", t(e.dataset.i18nPh)); });
  }
  // Message for an API error key (falls back to a generic one).
  function errMsg(key) {
    const k = "err." + key;
    return (D[lang][k] || D.fr[k]) ? t(k) : t("err.internal");
  }
  window.I18N = { t: t, tp: tp, setLang: setLang, detect: detect, apply: apply, errMsg: errMsg, get lang() { return lang; } };
